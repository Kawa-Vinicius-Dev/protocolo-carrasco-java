package exercicios.m01_fundamentos.exercicio026;

//26. Imprima números de 1 a 100.

public class Main {
    public static void main(String[] args) {
        contar1a100();
    }

    public static void contar1a100() {
        for (int i = 1; i <= 100; i++) {
            System.out.println(i);
        }
    }
}